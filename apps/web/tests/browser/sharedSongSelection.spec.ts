import { test, expect } from '@playwright/test'

test('预览模块迟到不会收起已打开的曲库或打断搜索', async ({ page }) => {
  let release!: () => void
  const ready = new Promise<void>(done => { release = done })
  await page.route(url => url.pathname === '/src/views/llll.ts', async route => {
    await ready
    await route.continue()
  })
  await page.route('**/assets/chart/**', route => route.fulfill({ status: 404, body: 'missing' }))
  await page.goto('/?song=103103&difficulty=HARD', { waitUntil: 'domcontentloaded' })
  await page.locator('#browse-library').click()
  const search = page.locator('#song-search')
  await search.fill('103119')
  release()
  await expect(page.locator('.now-playing .picker')).toBeVisible()
  await expect(page.locator('#song-panel')).toBeVisible()
  await expect(search).toBeFocused()
  await expect(search).toHaveValue('103119')
  await search.press('Enter')
  await expect(page.locator('.picker')).toHaveAttribute('data-song-id', '103119')
  await expect(page.locator('#browse-library')).toBeFocused()
  expect(new URL(page.url()).searchParams.get('song')).toBe('103119')
})

test('选择无谱歌曲后，共享来源提示跟随实际选择', async ({ page }) => {
  await page.route('**/assets/chart/**', route => route.fulfill({ status: 404, body: 'test missing' }))
  await page.goto('/?song=103103&difficulty=MASTER')
  await expect(page.locator('.picker')).toHaveAttribute('data-song-id', '103103')
  await page.locator('#browse-library').click()
  await page.getByLabel('含无谱面').focus()
  await page.keyboard.press('Space')
  await page.locator('#song-search').fill('104119')
  await page.locator('#song-search').press('Enter')
  await expect(page.locator('.picker')).toHaveAttribute('data-song-id', '104119')
  await expect(page.locator('#source-status')).toContainText('请打开自制谱')
  expect(new URL(page.url()).searchParams.has('difficulty')).toBe(false)
})

for (const view of ['llll', 'pjsk']) {
  test(`${view} 专注预览中打开曲库不展开档案，选择与关闭恢复入口焦点`, async ({ page }) => {
    await page.route('**/assets/chart/**', route => route.fulfill({ status: 404, body: 'missing' }))
    await page.goto(`/?view=${view}&song=103103&difficulty=HARD`)
    await expect(page.locator('.picker')).toHaveAttribute('data-song-id', '103103')
    const focusToggle = page.locator('[data-focus-toggle]')
    await focusToggle.click()
    await expect(page.locator('.workspace')).toHaveClass(/is-focused/)
    await expect(page.locator('.now-playing')).toBeHidden()

    const search = page.locator('#song-search')
    await page.keyboard.press('/')
    await expect(search).toBeFocused()
    await expect(search).toHaveValue('')
    await expect(page.locator('.workspace')).toHaveClass(/is-focused/)
    await expect(page.locator('.now-playing')).toBeHidden()
    await search.fill('103119')
    await search.press('Enter')
    await expect(page.locator('.picker')).toHaveAttribute('data-song-id', '103119')
    await expect(page.locator('#song-difficulty [data-difficulty="HARD"]')).toHaveAttribute('aria-checked', 'true')
    await expect.poll(() => new URL(page.url()).searchParams.get('song')).toBe('103119')
    expect(new URL(page.url()).searchParams.get('difficulty')).toBe('HARD')
    expect(new URL(page.url()).searchParams.get('view')).toBe(view)
    await expect(page.locator('#song-panel')).toBeHidden()
    await expect(focusToggle).toBeFocused()
    await expect(page.locator('.workspace')).toHaveClass(/is-focused/)
    await expect(page.locator('.now-playing')).toBeHidden()

    const title = page.locator('[data-library-open]')
    await title.click()
    await expect(search).toHaveValue('103119')
    await search.press('Escape')
    await expect(page.locator('#song-panel')).toBeHidden()
    await expect(title).toBeFocused()
    await title.click()
    await page.locator('#time').click()
    await expect(page.locator('#song-panel')).toBeHidden()
    await expect(page.locator('.workspace')).toHaveClass(/is-focused/)
  })
}
