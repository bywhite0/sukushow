import { expect, test } from '@playwright/test';

test('PJSK 曲终等待 BGM，2D MV 参与实时与导出渲染', async ({ page }) => {
  test.setTimeout(180_000);
  await page.goto('/?view=pjsk&song=103103&difficulty=MASTER');
  await page.waitForFunction(() => Boolean((window as any).__LLL_PJSK__?.getChart?.()), null, { timeout: 90_000 });
  const timing = await page.evaluate(() => {
    const p = (window as any).__LLL_PJSK__.player;
    const s = p.getStateSnapshot();
    const audio = p.getAudioSources();
    return { ...s, bgmEnd: audio.bgmStartSec + audio.bgm.duration };
  });
  expect(timing.apStartSec).toBeGreaterThanOrEqual(timing.bgmEnd);
  expect(timing.apStartSec).toBeGreaterThanOrEqual(timing.effectiveLeadInSec + 75.727);
  await expect(page.locator('#timeline')).toHaveAttribute('max', String(timing.durationSec));
  await page.locator('#tab-display').click();
  await expect(page.locator('#opt-mv')).toBeChecked();
  const frames = await page.evaluate(async () => {
    const { player, musicVideo } = (window as any).__LLL_PJSK__;
    player.pause();
    musicVideo.beginExport();
    player.setExportMode(true);
    const lead = player.getStateSnapshot().effectiveLeadInSec;
    const video = await musicVideo.seekFrame(2);
    if (!video) throw new Error('MV 未就绪');
    const muted = video.muted;
    const canvas = document.querySelector('#chart-canvas') as HTMLCanvasElement;
    player.setMusicVideoFrame(null);
    player.renderFrameAt(lead + 2, false);
    const background = canvas.toDataURL();
    player.setMusicVideoFrame(video);
    player.renderFrameAt(lead + 2, false);
    const movie = canvas.toDataURL();
    player.setMusicVideoFrame(null);
    player.renderFrameAt(lead + 2, false);
    const restored = canvas.toDataURL();
    player.setMusicVideoFrame(null, true);
    player.renderFrameAt(lead + 2, false);
    const gap = canvas.toDataURL();
    const before = await musicVideo.seekFrame(-1);
    const after = await musicVideo.seekFrame(90);
    musicVideo.endExport();
    player.setExportMode(false);
    return { muted, background, movie, restored, gap, before, after };
  });
  expect(frames.muted).toBe(true);
  expect(frames.movie).not.toBe(frames.background);
  expect(frames.restored).toBe(frames.background);
  expect(frames.gap).not.toBe(frames.background);
  expect(frames.before).toBeNull();
  expect(frames.after).toBeNull();
  await page.locator('#rate').selectOption('2');
  await page.evaluate(() => (window as any).__LLL_PJSK__.player.seek(11));
  await page.locator('#export-video').click();
  await page.locator('[name="resolution"]').selectOption('720p');
  await page.locator('[name="fps"]').selectOption('30');
  await page.locator('[name="start"]').fill('11');
  await page.locator('[name="end"]').fill('11.2');
  await page.locator('[data-start]').click();
  await expect(page.locator('[data-download]')).toBeVisible({ timeout: 60_000 });
  await expect(page.locator('[data-progress-text]')).toContainText('6 帧 / 0.20 秒');
  await page.locator('[data-close]').click();
  await expect(page.locator('#rate')).toHaveValue('2');
  expect(await page.evaluate(() => (window as any).__LLL_PJSK__.player.getStateSnapshot().currentTimeSec)).toBe(11);
  await page.locator('#opt-mv').uncheck();
  await page.reload();
  await page.waitForFunction(() => Boolean((window as any).__LLL_PJSK__?.getChart?.()), null, { timeout: 90_000 });
  await page.locator('#tab-display').click();
  await expect(page.locator('#opt-mv')).not.toBeChecked();
});
