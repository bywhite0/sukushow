import { test, expect } from '@playwright/test'

for (const view of ['llll', 'pjsk']) {
  test(`${view} Another Vocal 通过键盘选择并同步 URL 与难度`, async ({ page }) => {
    await page.route('**/assets/chart/**', route => route.fulfill({ status: 404, body: 'missing' }))
    await page.goto(`/?view=${view}&song=105101&difficulty=HARD`)
    const toggle = page.getByRole('button', { name: /演唱版本/ })
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await toggle.focus()
    await page.keyboard.press('ArrowDown')
    const version = page.locator('#song-versions [data-song-id="103112"]')
    await expect(page.locator('#song-version-panel')).toBeVisible()
    await expect(version).toContainText('Dream Believers')
    await expect(version).toContainText('蓮ノ空女学院スクールアイドルクラブ')
    await version.focus()
    await page.keyboard.press('Enter')
    await expect(page.locator('#song-search')).toHaveValue('Dream Believers')
    await expect(version).toHaveAttribute('aria-checked', 'true')
    await expect(toggle).toBeFocused()
    await expect(page.locator('#song-version-panel')).toBeHidden()
    await expect(page.locator('#song-difficulty [data-difficulty="HARD"]')).toHaveAttribute('aria-checked', 'true')
    expect(new URL(page.url()).searchParams.get('song')).toBe('103112')
    await toggle.press('Enter')
    await page.keyboard.press('Home')
    await page.keyboard.press('Space')
    await expect(page.locator('#song-versions [data-song-id="105101"]')).toHaveAttribute('aria-checked', 'true')
    expect(new URL(page.url()).searchParams.get('song')).toBe('105101')
  })
}

test('版本菜单支持方向键、Escape、外部点击和 Tab 离开', async ({ page }) => {
  await page.route('**/assets/chart/**', route => route.fulfill({ status: 404, body: 'missing' }))
  await page.goto('/?song=105101&difficulty=HARD')
  const toggle = page.getByRole('button', { name: /演唱版本/ })
  const panel = page.locator('#song-version-panel')
  await toggle.click()
  await expect(page.locator('#song-versions [data-song-id="105101"]')).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.locator('#song-versions [data-song-id="103101"]')).toBeFocused()
  await page.keyboard.press('End')
  await expect(page.locator('#song-versions [data-song-id="405141"]')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(panel).toBeHidden()
  await expect(toggle).toBeFocused()
  await toggle.click()
  await page.locator('#open-chart').focus()
  await expect(panel).toBeHidden()
  await toggle.click()
  await page.keyboard.press('Tab')
  await expect(panel).toBeHidden()
  await toggle.click()
  await page.locator('.brand').click({ position: { x: 2, y: 2 }, modifiers: ['Control'] })
  await expect(panel).toBeHidden()
  expect(new URL(page.url()).searchParams.get('song')).toBe('105101')
})

test('无兼容版本时隐藏入口，打开选曲时收起版本菜单', async ({ page }) => {
  await page.route('**/assets/chart/**', route => route.fulfill({ status: 404, body: 'missing' }))
  await page.goto('/?song=105101')
  await page.getByRole('button', { name: /演唱版本/ }).click()
  await page.locator('#song-search').click()
  await expect(page.locator('#song-version-panel')).toBeHidden()
  await page.locator('#song-search').fill('103103')
  await page.locator('.song-option[data-song-id="103103"]').click()
  await expect(page.locator('#song-versions')).toBeHidden()
})
